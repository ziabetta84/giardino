-- Cultivar rimaste in forma "Genere 'X'" (nome_scientifico con la specie, per questo il lotto 11 le aveva saltate):
-- 134 prendono il nome italiano del genere; 4 doppioni di cultivar già presenti sotto la specie
-- (bozze senza piante né figli) vengono cancellati. Rollback: scripts/nomi-italiani/rollback_hedera_residue.sql
update specie set nome = 'Edera' where slug = 'hedera' and nome = 'Hedera'
  and not exists (select 1 from specie o where o.nome = 'Edera');

